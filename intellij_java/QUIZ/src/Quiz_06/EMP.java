package Quiz_06;

public class EMP {

    int 사원번호;
    String 이름;
    String 직급;
    int 연봉;
    int 상사의_사원번호;

    EMP(int 사원번호, String 이름, String 직급, int 연봉, int 상사의_사원번호){
        this.사원번호 = 사원번호;
        this.이름 = 이름;
        this.직급 = 직급;
        this.연봉 = 연봉;
        this.상사의_사원번호 = 상사의_사원번호;
    }


}
